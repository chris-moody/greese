#!/usr/bin/env node
/**
 * Writes src/palette.ts: GreeseUI's palette, 22 hues in 11 shades from 50
 * (lightest) to 999 (darkest), generated from the curves below. The values are
 * this project's own: each shade is an OKLCH color (a lightness from the
 * shared curve, a chroma from the hue's peak, a hue angle), pulled into the sRGB
 * gamut, so every hue steps the same way and names mean one thing.
 *
 *   node scripts/generate-palette.ts
 *
 * Change a curve here and rerun it; the tests check the result.
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 999] as const

/** Lightness of each shade, before a hue's lift. 600 and 400 carry white and near-black text. */
const L = [0.975, 0.945, 0.9, 0.838, 0.76, 0.668, 0.565, 0.475, 0.395, 0.316, 0.2]
/** How much of a hue's peak chroma each shade keeps. */
const C = [0.1, 0.22, 0.42, 0.65, 0.88, 1, 0.97, 0.88, 0.74, 0.58, 0.4]
/** Where the lift applies: it fades toward both ends, so pale and dark shades stay in line. */
const BELL = [0, 0, 0.35, 0.8, 1, 1, 0.9, 0.6, 0.3, 0.1, 0]

/** Where `pale` applies: the light shades only. */
const PALE = [1, 1, 1, 0.6, 0.2, 0, 0, 0, 0, 0, 0]

interface Hue {
  /** OKLCH hue angle, degrees. */
  h: number
  /** Peak chroma. */
  c: number
  /** Lightness added to the middle shades, for hues that read dull at the shared curve. */
  lift?: number
  /** Multiplies the chroma of the light shades, for hues whose pale tints look grey. */
  pale?: number
}

/** The palette, in order: greys coolest first, then around the color wheel from red. */
const hues: Record<string, Hue> = {
  steel: { h: 250, c: 0.034 },
  gray: { h: 0, c: 0 },
  silver: { h: 230, c: 0.013 },
  ash: { h: 95, c: 0.012 },
  taupe: { h: 60, c: 0.028 },
  red: { h: 27, c: 0.215 },
  orange: { h: 52, c: 0.19, lift: 0.025, pale: 1.2 },
  gold: { h: 78, c: 0.165, lift: 0.07, pale: 1.3 },
  yellow: { h: 100, c: 0.175, lift: 0.12, pale: 1.9 },
  lime: { h: 128, c: 0.19, lift: 0.07, pale: 1.3 },
  green: { h: 150, c: 0.175, lift: 0.01 },
  jade: { h: 166, c: 0.145, lift: 0.01 },
  turquoise: { h: 188, c: 0.118, lift: 0.025 },
  aqua: { h: 206, c: 0.115, lift: 0.04 },
  azure: { h: 235, c: 0.14, lift: 0.01 },
  blue: { h: 259, c: 0.19 },
  royal: { h: 275, c: 0.2 },
  lavender: { h: 294, c: 0.18 },
  purple: { h: 313, c: 0.2 },
  magenta: { h: 336, c: 0.215 },
  pink: { h: 355, c: 0.185 },
  ruby: { h: 12, c: 0.21 },
}

// --- OKLCH → sRGB ---------------------------------------------------------

const toLinear = (l: number, a: number, b: number): [number, number, number] => {
  const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3
  return [
    4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
    -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
    -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
  ]
}

const inGamut = (rgb: number[]) => rgb.every((v) => v >= -0.0005 && v <= 1.0005)
const encode = (v: number) => {
  const c = Math.min(1, Math.max(0, v))
  return c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055
}

/** An OKLCH color as `#rrggbb`, its chroma reduced until it fits sRGB. */
const hex = (l: number, c: number, h: number): string => {
  const rad = (h * Math.PI) / 180
  let lo = 0
  let hi = c
  const at = (chroma: number) =>
    toLinear(l, chroma * Math.cos(rad), chroma * Math.sin(rad))
  if (inGamut(at(c))) lo = c
  else
    for (let i = 0; i < 24; i++) {
      const mid = (lo + hi) / 2
      if (inGamut(at(mid))) lo = mid
      else hi = mid
    }
  return `#${at(lo)
    .map((v) =>
      Math.round(encode(v) * 255)
        .toString(16)
        .padStart(2, '0')
    )
    .join('')}`
}

// --- output ---------------------------------------------------------------

const lines: string[] = []
for (const [name, { h, c, lift = 0, pale = 1 }] of Object.entries(hues)) {
  let previous = 1
  const rows = SHADES.map((shade, i) => {
    // Always darker than the shade before it, whatever the lift.
    const lightness = Math.min(previous - 0.02, L[i]! + lift * BELL[i]!)
    previous = lightness
    return `  ${shade}: '${hex(lightness, c * C[i]! * (1 + (pale - 1) * PALE[i]!), h)}',`
  })
  lines.push(`export const ${name} = {\n${rows.join('\n')}\n} as const satisfies Hue`)
}

const header = `/**
 * The color palette: 22 hues, each in 11 shades from 50 (lightest) to 999
 * (darkest), like MUI's \`colors\`. GENERATED by scripts/generate-palette.ts: the
 * values are fixed, so a palette name means the same color in TypeScript, the
 * SCSS kit and CSS.
 *
 * The semantic roles in tokens.ts are built from these, and you can use them
 * wherever a color goes, without hex literals:
 *
 * - TypeScript: \`palette.lavender[600]\`, or import one hue: \`lavender[600]\`.
 * - The SCSS kit: \`lavender-600\` as a token value, or \`greese.palette(lavender, 600)\`.
 * - CSS: \`var(--greese-lavender-600)\`, with \`@greese/ui/palette.css\`.
 *
 * Each hue is its own export, so a bundle keeps only the hues it imports.
 */

/** Shades, lightest first: \`--greese-<hue>-<shade>\`. */
export const paletteShades = [${SHADES.join(', ')}] as const

export type PaletteShade = (typeof paletteShades)[number]

/** One hue: a color per shade. */
export type Hue = Readonly<Record<PaletteShade, string>>

// Greys first, then around the color wheel.
`

const names = Object.keys(hues)
const footer = `
/** Every hue by name, for lookups by a name that's only known at run time. */
export const palette = {
  ${names.join(',\n  ')},
} as const

export type PaletteHue = keyof typeof palette
`
const out = join(dirname(fileURLToPath(import.meta.url)), '../src/palette.ts')
writeFileSync(out, `${header}${lines.join('\n')}\n${footer}`)
console.log(`wrote ${out}: ${names.length} hues`)
