#!/usr/bin/env node
/**
 * Emits dist/tokens.css, dist/palette.css and the SCSS modules from
 * src/tokens.ts and src/palette.ts.
 *
 * The token module is imported, not parsed, so the output always reflects the
 * real values. Node 24 strips the types, so this needs no build step of its own.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { breakpoints, color, scalarTokens, type ScalarGroup } from '../src/tokens.ts'
import { palette } from '../src/palette.ts'
import {
  effectClass,
  effectNames,
  effectPlan,
  effectDirections,
  entranceNames,
  exitNames,
} from '../src/effects.ts'
import {
  cssProperty,
  typeProps,
  typography,
  typographyByBreakpoint,
  typeVariants,
} from '../src/typography.ts'
import {
  allDurationKeys,
  cssVar,
  kebab,
  decls,
  LAYER_ORDER,
  MOTION_ATTR,
  reducedMotionDecls,
  SCHEME_ATTR,
  THEME_ATTR,
  type Declarations,
} from '../src/css.ts'

const DIST = join(dirname(fileURLToPath(import.meta.url)), '../dist')

const colorDecls = (mode: 'light' | 'dark'): Declarations => [
  ['color-scheme', mode],
  ...Object.entries(color).map(([role, pair]): [string, string] => [
    cssVar('color', role),
    pair[mode],
  ]),
]

const scalarDecls: Declarations = Object.entries(scalarTokens).flatMap(
  ([group, values]) =>
    Object.entries(values).map(([key, value]): [string, string] => [
      cssVar(group as ScalarGroup, key),
      value,
    ])
)

/*
 * The breakpoints as custom properties, `--greese-breakpoint-md: 900px`, and
 * their keys, `--greese-breakpoint-keys: xs sm md lg xl`, for CSS and
 * JavaScript to read (media queries can't use them; `configureBreakpoints()`
 * does). They're fixed when the stylesheet is built, so they sit outside the
 * themable tokens. The Sass build writes its own (_breakpoint-vars.scss), from
 * the breakpoints it's built with.
 */
const breakpointDecls: Declarations = [
  ...Object.entries(breakpoints).map(([key, value]): [string, string] => [
    `--greese-breakpoint-${key}`,
    `${value}px`,
  ]),
  ['--greese-breakpoint-keys', Object.keys(breakpoints).join(' ')],
]

/*
 * The type system's custom properties: the smallest screen's values with the
 * rest of `:root`, and a media query per breakpoint that changes any (static
 * px, the defaults' breakpoints; a build with its own redeclares them).
 */
const typeSteps = typographyByBreakpoint(typography)
const typeBase: Declarations = typeSteps
  .filter(([min]) => min === 0)
  .flatMap(([, d]) => d)
const typeMedia = typeSteps
  .filter(([min]) => min > 0)
  .map(
    ([min, d]) => `
  @media (width >= ${min}px) {
    :root {
${decls(d, '      ')}
    }
  }`
  )
  .join('\n')

const S = (value: string): string => `[${SCHEME_ATTR}='${value}']`
const MOTION_REDUCE = `[${MOTION_ATTR}='reduce']`

// ASCII only: a non-ASCII character makes Sass prepend @charset to the output.
const header = `/* GENERATED by @greese/ui from src/tokens.ts - do not edit. */`

/*
 * Colors follow the OS by default. [data-greese-scheme] on any element forces
 * 'light' | 'dark' for that subtree, or 'system' to return to the OS setting.
 *
 * Each scheme redeclares the color variables rather than using light-dark():
 * consumer bundlers targeting older browsers (Vite's default Lightning CSS
 * target, for one) polyfill light-dark() by substituting at the declaring
 * element, which freezes :root tokens and breaks nested schemes. Plain
 * redeclaration survives any transpiler. See docs/adr/0002.
 */
// The utilities block after the tokens: reduced motion the app asks for
// (`data-greese-motion="reduce"`, ThemeProvider's `motion`), whatever the
// system's setting (ADR 0033). The durations collapse as they do for the
// system's, on the subtree and on any theme inside it; nothing else animates,
// transitions or scrolls smoothly; set on the root, page transitions cut too.
// In the last layer, so it outranks every component, while the app's own
// unlayered CSS still wins.
const bodyOf = (full: boolean): string => `@layer greese.tokens {
  :root {
${decls([['--greese-loaded', '1'], ...scalarDecls, ...(full ? [...breakpointDecls, ...typeBase] : [])], '    ')}
  }
${full ? typeMedia : ''}

  :root,
  ${S('light')},
  ${S('system')} {
${decls(colorDecls('light'), '    ')}
  }

  @media (prefers-color-scheme: dark) {
    :root:not(${S('light')}),
    ${S('system')} {
${decls(colorDecls('dark'), '      ')}
    }
  }

  ${S('dark')} {
${decls(colorDecls('dark'), '    ')}
  }

  @media (prefers-reduced-motion: reduce) {
    :root {
${decls(reducedMotionDecls(allDurationKeys), '      ')}
    }
  }
}

@layer greese.utilities {
  ${MOTION_REDUCE},
  ${MOTION_REDUCE} [${THEME_ATTR}] {
${decls(reducedMotionDecls(allDurationKeys), '    ')}
  }

  ${MOTION_REDUCE},
  ${MOTION_REDUCE} *,
  ${MOTION_REDUCE} ::before,
  ${MOTION_REDUCE} ::after {
    animation-duration: 0.01ms;
    animation-delay: 0s;
    animation-iteration-count: 1;
    transition-duration: 0.01ms;
    transition-delay: 0s;
    scroll-behavior: auto;
  }

  :root${MOTION_REDUCE}::view-transition-group(*),
  :root${MOTION_REDUCE}::view-transition-old(*),
  :root${MOTION_REDUCE}::view-transition-new(*) {
    animation-duration: 0.01ms;
    animation-delay: 0s;
  }
}
`

const css = `${header}\n${LAYER_ORDER}\n${bodyOf(true)}`

const scssMap = (entries: Array<[string, string]>): string =>
  `(\n${entries.map(([k, v]) => `  '${k}': ${v},`).join('\n')}\n)`

// Values as quoted strings (font stacks hold commas and quotes); the SCSS kit
// unquotes them when it writes a declaration.
const q = (value: string): string => JSON.stringify(value)

const colorMap = scssMap(
  Object.entries(color).map(([role, pair]) => [
    kebab(role),
    `(light: ${q(pair.light)}, dark: ${q(pair.dark)})`,
  ])
)

const scalarMap = scssMap(
  Object.entries(scalarTokens).map(([group, values]) => [
    kebab(group),
    scssMap(Object.entries(values).map(([key, value]) => [kebab(key), q(value)])).replace(
      /\n/g,
      '\n  '
    ),
  ])
)

const maps = `$breakpoints: ${scssMap(Object.entries(breakpoints).map(([k, v]) => [k, `${v}px`]))};

$space-keys: (${Object.keys(scalarTokens.space).join(', ')});

// Every token's default, keyed as in its custom property: (accent: (light, dark)).
$color: ${colorMap};

// Scheme-independent groups: (font-size: (lg: '1.125rem'), ...).
$scalars: ${scalarMap};

// The palette: (lavender: (600: #805dd3, ...), ...), for the kit's palette().
$palette: ${scssMap(
  Object.entries(palette).map(([name, shades]) => [
    name,
    `(${Object.entries(shades)
      .map(([shade, value]) => `${shade}: ${value}`)
      .join(', ')})`,
  ])
)};

// The type system: variant -> (base | breakpoint key) -> (prop: value).
$typography: ${scssMap(
  typeVariants.map((variant) => [
    variant,
    scssMap(
      Object.entries(typography[variant]).map(([point, style]) => [
        point,
        scssMap(
          Object.entries(style).map(([prop, value]) => [cssProperty(prop), q(value)])
        ),
      ])
    ).replace(/\n/g, '\n  '),
  ])
)};

// The type properties, named as the CSS properties they set.
$type-props: (${typeProps.map(cssProperty).join(', ')});

// The greese prop effects, from src/effects.ts: name -> (enter: step -> (property:
// value)) for those that end at rest (Motion.scss writes their @keyframes), or
// (exit: (property: value), leave: step -> (property: value)) for those that
// end away from it (the custom properties an overlay's exit sets, and the
// keyframes a page transition's old snapshot plays). The kit's motion() takes
// these names.
$effects: ${scssMap(
  effectNames.map((name) => {
    const { enter, exit, leave } = effectPlan(name)
    const declarations = (values: Record<string, string>) =>
      scssMap(Object.entries(values).map(([property, value]) => [property, q(value)]))
    return [
      effectClass(name),
      enter
        ? `(enter: ${scssMap(enter.map(([at, values]) => [at, declarations(values)])).replace(/\n/g, '\n  ')})`
        : `(exit: ${Object.keys(exit).length ? declarations(exit) : '()'}, leave: ${scssMap(
            (leave ?? []).map(([at, values]) => [at, declarations(values)])
          ).replace(/\n/g, '\n  ')})`,
    ]
  })
)};

// The cascade layer order, for stylesheets that emit it themselves.
$layer-order: '${LAYER_ORDER.replace(/^@layer |;$/g, '')}';
`

const scss = `${header}
// Build-time values for greese ui's SCSS. Using this module also emits the layer
// order and the custom properties, exactly once, wherever it is first used.

${maps}
${LAYER_ORDER}
${bodyOf(true)}`

// The same without the breakpoints' and the type system's custom properties,
// for the stylesheet build, which writes those itself from its own breakpoints
// and typography.
const scssBase = `${header}
// Internal: the tokens without the breakpoints (src/styles/_breakpoint-vars.scss)
// or the type system (src/styles/_typography-vars.scss).
${LAYER_ORDER}
${bodyOf(false)}`

/*
 * The palette as custom properties, opt-in: 242 colors most pages never
 * use, so they stay out of tokens.css. They don't change with the scheme.
 */
const paletteCss = `${header}
/* Opt-in: @import '@greese/ui/palette.css';  then  var(--greese-lavender-600). */
${LAYER_ORDER}
@layer greese.tokens {
  :root {
${Object.entries(palette)
  .map(([name, shades]) =>
    Object.entries(shades)
      .map(([shade, value]) => `    --greese-${name}-${shade}: ${value};`)
      .join('\n')
  )
  .join('\n')}
  }
}
`

mkdirSync(DIST, { recursive: true })
writeFileSync(join(DIST, 'palette.css'), paletteCss)
writeFileSync(join(DIST, 'tokens.css'), css)
writeFileSync(join(DIST, '_tokens.scss'), scss)
writeFileSync(join(DIST, '_tokens-base.scss'), scssBase)
// Layer order alone, for stylesheets that must declare it without the tokens.
writeFileSync(join(DIST, '_layers.scss'), `${header}\n${LAYER_ORDER}\n`)
// Sass values only, emitting no CSS: safe to use from any partial.
writeFileSync(
  join(DIST, '_maps.scss'),
  `// GENERATED by @greese/ui from src/tokens.ts - do not edit.\n${maps}`
)

// The class-name suffix of each CSS-played effect, for the React resolver, which
// must know them without carrying the effects' keyframes (a few hundred bytes in
// every component bundle). Generated from the same source, so there is no list.
// The wipes and pockets are a prefix in eight directions each: written as the
// prefixes and the directions, they cost a few bytes instead of 32 names in
// every component.
const DIRS = `const D = ${JSON.stringify(effectDirections)}`
const list = (names: readonly string[]): string => {
  // Names that follow a direction, as prefixes: every direction (`D`, wipes,
  // irises, pockets), or the four sides only (`D.slice(0, 4)`, flips).
  const sides = effectDirections.slice(0, 4)
  const candidates = [
    ...new Set(names.map((n) => /^([a-z]+(?:Out)?)(?=Right|Left|Up|Down)/.exec(n)?.[1])),
  ].filter((p): p is string => !!p)
  const every = candidates.filter((p) =>
    effectDirections.every((d) => names.includes(`${p}${d}`))
  )
  const four = candidates.filter(
    (p) => !every.includes(p) && sides.every((d) => names.includes(`${p}${d}`))
  )
  const grouped = new Set([
    ...every.flatMap((p) => effectDirections.map((d) => `${p}${d}`)),
    ...four.flatMap((p) => sides.map((d) => `${p}${d}`)),
  ])
  const rest = names.filter((n) => !grouped.has(n))
  const parts = [
    `...${JSON.stringify(rest)}`,
    ...(every.length
      ? [`...${JSON.stringify(every)}.flatMap((p) => D.map((d) => p + d))`]
      : []),
    ...(four.length
      ? [`...${JSON.stringify(four)}.flatMap((p) => D.slice(0, 4).map((d) => p + d))`]
      : []),
  ]
  return grouped.size ? `[${parts.join(', ')}]` : JSON.stringify(names)
}
const generated = '// GENERATED by @greese/ui from src/effects.ts - do not edit.'
writeFileSync(
  join(DIST, 'effect-classes.js'),
  `${generated}
${DIRS}
export const entranceNames = ${list(entranceNames())}
export const exitNames = ${list(exitNames())}
export const effectClass = (name) => name.replace(/[A-Z]/g, (c) => \`-\${c.toLowerCase()}\`)
`
)
writeFileSync(
  join(DIST, 'effect-classes.d.ts'),
  `${generated}
import type { BuiltInEffect } from './effects.js'
/** The entrances CSS plays alone. */
export declare const entranceNames: readonly BuiltInEffect[]
/** The built-in effects an overlay leaves with in CSS: those that end away from rest. */
export declare const exitNames: readonly BuiltInEffect[]
/** \`fadeUp\` → \`fade-up\`: the suffix of its \`greese-Motion--enter-*\` class. */
export declare const effectClass: (name: string) => string
`
)
console.log(
  'wrote dist/effect-classes.js, dist/tokens.css, dist/palette.css, dist/_tokens.scss, dist/_tokens-base.scss, dist/_layers.scss, dist/_maps.scss'
)
