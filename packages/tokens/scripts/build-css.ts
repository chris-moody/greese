#!/usr/bin/env node
/**
 * Emits dist/tokens.css, dist/palette.css and the SCSS modules from
 * src/tokens.ts and src/palette.ts.
 *
 * The token module is imported, not parsed, so the output always reflects the
 * real values. Node 24 strips the types, so this needs no build step of its own.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { breakpoints, color, scalarTokens, type ScalarGroup } from '../src/tokens.ts'
import { palette } from '../src/palette.ts'
import {
  allDurationKeys,
  cssVar,
  kebab,
  decls,
  LAYER_ORDER,
  reducedMotionDecls,
  SCHEME_ATTR,
  type Declarations,
} from '../src/css.ts'

const DIST = join(dirname(fileURLToPath(import.meta.url)), '../dist')

const colorDecls = (mode: 'light' | 'dark'): Declarations => [
  ['color-scheme', mode],
  ...Object.entries(color).map(([role, pair]): [string, string] => [
    cssVar('color', role),
    pair[mode],
  ]),
]

const scalarDecls: Declarations = Object.entries(scalarTokens).flatMap(
  ([group, values]) =>
    Object.entries(values).map(([key, value]): [string, string] => [
      cssVar(group as ScalarGroup, key),
      value,
    ])
)

const S = (value: string): string => `[${SCHEME_ATTR}='${value}']`

// ASCII only: a non-ASCII character makes Sass prepend @charset to the output.
const header = `/* GENERATED by @greese-ui/tokens from src/tokens.ts - do not edit. */`

/*
 * Colours follow the OS by default. [data-greese-scheme] on any element forces
 * 'light' | 'dark' for that subtree, or 'system' to return to the OS setting.
 *
 * Each scheme redeclares the colour variables rather than using light-dark():
 * consumer bundlers targeting older browsers (Vite's default Lightning CSS
 * target, for one) polyfill light-dark() by substituting at the declaring
 * element, which freezes :root tokens and breaks nested schemes. Plain
 * redeclaration survives any transpiler. See docs/adr/0002.
 */
const body = `@layer greese.tokens {
  :root {
${decls([['--greese-loaded', '1'], ...scalarDecls], '    ')}
  }

  :root,
  ${S('light')},
  ${S('system')} {
${decls(colorDecls('light'), '    ')}
  }

  @media (prefers-color-scheme: dark) {
    :root:not(${S('light')}),
    ${S('system')} {
${decls(colorDecls('dark'), '      ')}
    }
  }

  ${S('dark')} {
${decls(colorDecls('dark'), '    ')}
  }

  @media (prefers-reduced-motion: reduce) {
    :root {
${decls(reducedMotionDecls(allDurationKeys), '      ')}
    }
  }
}
`

const css = `${header}\n${LAYER_ORDER}\n${body}`

const scssMap = (entries: Array<[string, string]>): string =>
  `(\n${entries.map(([k, v]) => `  '${k}': ${v},`).join('\n')}\n)`

// Values as quoted strings (font stacks hold commas and quotes); the SCSS kit
// unquotes them when it writes a declaration.
const q = (value: string): string => JSON.stringify(value)

const colorMap = scssMap(
  Object.entries(color).map(([role, pair]) => [
    kebab(role),
    `(light: ${q(pair.light)}, dark: ${q(pair.dark)})`,
  ])
)

const scalarMap = scssMap(
  Object.entries(scalarTokens).map(([group, values]) => [
    kebab(group),
    scssMap(Object.entries(values).map(([key, value]) => [kebab(key), q(value)])).replace(
      /\n/g,
      '\n  '
    ),
  ])
)

const maps = `$breakpoints: ${scssMap(Object.entries(breakpoints).map(([k, v]) => [k, `${v}px`]))};

$space-keys: (${Object.keys(scalarTokens.space).join(', ')});

// Every token's default, keyed as in its custom property: (accent: (light, dark)).
$color: ${colorMap};

// Scheme-independent groups: (font-size: (lg: '1.125rem'), ...).
$scalars: ${scalarMap};

// The palette: (violet: (600: #7c3aed, ...), ...), for the kit's palette().
$palette: ${scssMap(
  Object.entries(palette).map(([name, shades]) => [
    name,
    `(${Object.entries(shades)
      .map(([shade, value]) => `${shade}: ${value}`)
      .join(', ')})`,
  ])
)};

// The cascade layer order, for stylesheets that emit it themselves.
$layer-order: '${LAYER_ORDER.replace(/^@layer |;$/g, '')}';
`

const scss = `${header}
// Build-time values for GreeseUI's SCSS. Using this module also emits the layer
// order and the custom properties, exactly once, wherever it is first used.

${maps}
${LAYER_ORDER}
${body}`

/*
 * The palette as custom properties, opt-in: 242 colours most pages never
 * use, so they stay out of tokens.css. They don't change with the scheme.
 */
const paletteCss = `${header}
/* Opt-in: @import '@greese-ui/tokens/palette.css';  then  var(--greese-lavender-600). */
${LAYER_ORDER}
@layer greese.tokens {
  :root {
${Object.entries(palette)
  .map(([name, shades]) =>
    Object.entries(shades)
      .map(([shade, value]) => `    --greese-${name}-${shade}: ${value};`)
      .join('\n')
  )
  .join('\n')}
  }
}
`

mkdirSync(DIST, { recursive: true })
writeFileSync(join(DIST, 'palette.css'), paletteCss)
writeFileSync(join(DIST, 'tokens.css'), css)
writeFileSync(join(DIST, '_tokens.scss'), scss)
// Layer order alone, for stylesheets that must declare it without the tokens.
writeFileSync(join(DIST, '_layers.scss'), `${header}\n${LAYER_ORDER}\n`)
// Sass values only, emitting no CSS: safe to use from any partial.
writeFileSync(
  join(DIST, '_maps.scss'),
  `// GENERATED by @greese-ui/tokens from src/tokens.ts - do not edit.\n${maps}`
)
console.log(
  'wrote dist/tokens.css, dist/palette.css, dist/_tokens.scss, dist/_layers.scss, dist/_maps.scss'
)
