import { specToLayout, type ThemeSpec } from '@greese/ui/theme-files'

/** A shape point's coordinate: a percentage of the box, moved in by a parameter. */
const at = (pct: number, k: 1 | -1, param?: string) => ({
  pct,
  px: 0,
  k,
  ...(param ? { param } : {}),
})

