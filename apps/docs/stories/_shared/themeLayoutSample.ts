/**
 * Theme Studio's `greese-theme.effects.ts` for `sampleSpec`. The studio
 * writes it (it's React's); apps/site checks this copy against it.
 */
export const sampleEffectsTs = `// Generated by greese ui Theme Studio from greese-theme.json. Edit it there, or in
// the studio (npm run studio); changes made here are overwritten.
// Import it once, at your app's entry, before anything renders.
import { defineGreeseEffect } from '@greese/react'

declare module '@greese/react' {
  interface GreeseEffectRegistry {
    floatUp: true
  }
}

defineGreeseEffect('floatUp', {
  keyframes: {
    opacity: [0, 1],
    y: ['1.5rem', '0px'],
  },
  duration: 0.6,
})
`

/** The theme's folder name, and the files saving writes beside it. */
export const SAMPLE_FOLDER = 'greese-theme'

/**
 * What Theme Studio saves for `sampleSpec`, by path: the theme file, the
 * effects module and the SCSS layout, exactly as `specToLayout()` writes it.
 * (The compiled `greese-theme.css` comes from Sass, so it isn't shown.)
 */
export const sampleFiles = (): Record<string, string> => ({
  'greese-theme.json': `${JSON.stringify(sampleSpec, null, 2)}\n`,
  'greese-theme.effects.ts': sampleEffectsTs,
  ...Object.fromEntries(
    Object.entries(specToLayout(sampleSpec, 'greese-theme.json')).map(([path, text]) => [
      `${SAMPLE_FOLDER}/${path}`,
      text,
    ])
  ),
})
